  public void initPathplanner() {
    // massKG = 68.4 assuming max weight
    // MOI is gotten from CAD, hopefully today,
    // ModuleConfig moduleConfic = new ModuleConfig(2in, MAX_SPEED, 1.1/*COF*/,
    // DCMotor.krakenX60,
    // 1))
    // TunerConstants...
    Translation2d[] moduleOffsets = new Translation2d[] {
        new Translation2d(TunerConstants.FrontLeft.LocationX, TunerConstants.FrontLeft.LocationY),
        new Translation2d(
            TunerConstants.FrontRight.LocationX, TunerConstants.FrontRight.LocationY),
        new Translation2d(TunerConstants.BackLeft.LocationX, TunerConstants.BackLeft.LocationY),
        new Translation2d(TunerConstants.BackRight.LocationX, TunerConstants.BackRight.LocationY)
    };
    RobotConfig config = new RobotConfig(ROBOT_MASS_KG, WHEEL_COF, MODULE_CONFIG, moduleOffsets);

    AutoBuilder.configure(
        () -> getState().Pose,
        this::resetPose,
        () -> getState().Speeds,
        (speeds, feedforwards) -> setControl(
            m_pathApplyRobotSpeeds
                .withSpeeds(speeds)
                .withWheelForceFeedforwardsX(feedforwards.robotRelativeForcesXNewtons())
                .withWheelForceFeedforwardsY(feedforwards.robotRelativeForcesYNewtons())),
        new PPHolonomicDriveController(
            new PIDConstants(DRIVE_P, DRIVE_I, DRIVE_D), // TODO: tune these drive pid constants
            new PIDConstants(
                ROTATION_P, ROTATION_I, ROTATION_D)
        ),
        config,
        () -> {
          var alliance = DriverStation.getAlliance();
          if (alliance.isPresent()) {
            return alliance.get() == DriverStation.Alliance.Red;
          }
          return false;
        },
        this);
  }


  public Command joystickDrive(
      DoubleSupplier joystickX, DoubleSupplier joystickY, DoubleSupplier joystickThetaX) {
    FieldCentric request = new SwerveRequest.FieldCentric()
        .withDeadband(0.0)
        .withRotationalDeadband(0.0)
        .withDriveRequestType(DriveRequestType.OpenLoopVoltage);
    return run(
        () -> this.setControl(
            request
                .withVelocityX(-joystickY.getAsDouble() * MAX_DRIVE_SPEED)
                .withVelocityY(-joystickX.getAsDouble() * MAX_DRIVE_SPEED)
                .withRotationalRate(-joystickThetaX.getAsDouble() * MAX_ROTATIONAL_SPEED)))
        .withName("Joystick Drive");
  }

  public Command pointTowardsPoint(
      Supplier<Translation2d> desiredPoint, DoubleSupplier joystickX, DoubleSupplier joystickY) {
    FieldCentricFacingAngle request = new SwerveRequest.FieldCentricFacingAngle()
        .withDriveRequestType(DriveRequestType.OpenLoopVoltage)
        .withDeadband(MAX_DRIVE_SPEED * 0.01)
        .withRotationalDeadband(MAX_ROTATIONAL_SPEED * 0.01);
    request.withHeadingPID(ROTATION_P, ROTATION_I, ROTATION_D);

    return defer(
        () -> run(() -> {
          Translation2d delta = desiredPoint.get().minus(getState().Pose.getTranslation());

          Rotation2d targetAngle = delta.getAngle().plus(isRedSide() ? Rotation2d.k180deg : Rotation2d.kZero);
          desriedAngle = targetAngle;
          this.setControl(
              request
                  .withVelocityX(-joystickY.getAsDouble() * MAX_DRIVE_SPEED)
                  .withVelocityY(-joystickX.getAsDouble() * MAX_DRIVE_SPEED)
                  .withTargetDirection(targetAngle));
        }));
  }

  public Command pidToPoint(Pose2d pose) {
    FieldCentricFacingAngle request = new SwerveRequest.FieldCentricFacingAngle()
        .withDriveRequestType(DriveRequestType.OpenLoopVoltage)
        .withHeadingPID(ROTATION_P, ROTATION_I, ROTATION_D);

    return run(
        () -> {
          double velX = drivePID.calculate(pose.getX(), getState().Pose.getX());
          double velY = drivePID.calculate(pose.getY(), getState().Pose.getY());

          this.setControl(
              request
                  .withVelocityX(velX)
                  .withVelocityY(velY)
                  .withTargetDirection(pose.getRotation().plus(Rotation2d.k180deg)));
        });
  }

  public Pose2d whereShoot() {
    if (getState().Pose.getY() > Units.inchesToMeters(158.5)
        && getState().Pose.getY() < FIELD_LENGTH_M - Units.inchesToMeters(158.5)) {
      return getState().Pose.nearest(getShuttlePoses());
    } else {
      return getHubLocation();
    }
  }

   public boolean isAtDesiredAngle() {
    Rotation2d checkAngle = desriedAngle;
    if(isRedSide()) {
      checkAngle = checkAngle.plus(Rotation2d.fromDegrees(180));
    }
    return (Math.abs(getState().Pose.getRotation().minus(checkAngle).getDegrees()) < 7);
   }

